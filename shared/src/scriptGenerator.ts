/* ─────────────────────────────────────────────
 *  Discord Automation Script Generator
 *
 *  Generates production-grade discord.js (v14) and discord.py (v2)
 *  automation scripts with dry-run support, idempotency, rate-limiting,
 *  and environment variable credentials.
 * ───────────────────────────────────────────── */

import type { ServerBlueprint } from "./index";
import type { ArchitectureProposal } from "./aiTypes";
import type { ServerTemplate } from "./templateTypes";

export interface ScriptGeneratorOptions {
  guildId?: string;
  dryRun?: boolean;
  createRoles?: boolean;
  createCategories?: boolean;
  createChannels?: boolean;
}

type ArchitectureSource = ServerBlueprint | ArchitectureProposal | ServerTemplate;

interface NormalizedItem {
  name: string;
  categories: {
    name: string;
    channels: {
      name: string;
      type: string;
      topic?: string;
      isStaffOnly?: boolean;
    }[];
  }[];
  roles: {
    name: string;
    color?: string;
    permissions: string[];
  }[];
}

function normalizeSource(source: ArchitectureSource): NormalizedItem {
  // If it's a ServerBlueprint
  if ("server" in source && "categories" in source && "channels" in source) {
    const bp = source as ServerBlueprint;
    const catMap = new Map<string, typeof bp.categories[0]>();
    for (const c of bp.categories) catMap.set(c.id, c);

    return {
      name: bp.server.name,
      categories: bp.categories.map((cat) => ({
        name: cat.name,
        channels: bp.channels
          .filter((ch) => ch.parentId === cat.id && ch.type !== "category")
          .map((ch) => ({
            name: ch.name,
            type: ch.type,
            topic: ch.topic,
            isStaffOnly: ch.visibilityAnalysis?.classification === "role-restricted",
          })),
      })),
      roles: bp.roles
        .filter((r) => r.name.toLowerCase() !== "@everyone" && r.position > 0)
        .map((r) => ({
          name: r.name,
          color: r.color,
          permissions: r.permissions || [],
        })),
    };
  }

  // If it's a ServerTemplate
  if ("categories" in source && "tags" in source) {
    const tmpl = source as ServerTemplate;
    return {
      name: tmpl.name,
      categories: tmpl.categories.map((c) => ({
        name: c.name,
        channels: c.channels.map((ch) => ({
          name: ch.name,
          type: ch.type,
          topic: ch.topic,
          isStaffOnly: ch.isStaffOnly,
        })),
      })),
      roles: (tmpl.roles || []).map((r) => ({
        name: r.name,
        color: r.color,
        permissions: r.permissions,
      })),
    };
  }

  // If it's an ArchitectureProposal
  const prop = source as ArchitectureProposal;
  const pCatMap = new Map<string, typeof prop.categories[0]>();
  for (const c of prop.categories) pCatMap.set(c.id, c);

  return {
    name: prop.title,
    categories: prop.categories.map((cat) => ({
      name: cat.name,
      channels: prop.channels
        .filter((ch) => ch.categoryId === cat.id)
        .map((ch) => ({
          name: ch.name,
          type: ch.type,
          topic: ch.topic,
          isStaffOnly: ch.suggestedVisibility === "role-restricted",
        })),
    })),
    roles: [],
  };
}

// ── Discord.js Generator ───────────────────────

export function generateDiscordJsScript(
  source: ArchitectureSource,
  options: ScriptGeneratorOptions = {}
): string {
  const norm = normalizeSource(source);
  const guildId = options.guildId || "YOUR_TARGET_GUILD_ID";
  const isDryRun = options.dryRun ?? false;

  return `/**
 * Discord Server Architecture Automation Script (discord.js v14)
 * Target Server: ${norm.name}
 * Generated by MapMyServer
 * 
 * PREREQUISITES:
 * 1. npm install discord.js dotenv
 * 2. Set DISCORD_BOT_TOKEN in your .env file
 * 3. Ensure your bot has ADMINISTRATOR or MANAGE_CHANNELS & MANAGE_ROLES
 * 
 * EXECUTION:
 * node apply-architecture.js ${isDryRun ? "--dry-run" : ""}
 */

const { Client, GatewayIntentBits, ChannelType, PermissionFlagsBits } = require("discord.js");
require("dotenv").config();

const TOKEN = process.env.DISCORD_BOT_TOKEN;
const GUILD_ID = process.env.DISCORD_GUILD_ID || "${guildId}";
const IS_DRY_RUN = process.argv.includes("--dry-run") || ${isDryRun};

if (!TOKEN) {
  console.error("ERROR: DISCORD_BOT_TOKEN is required in your environment variables.");
  process.exit(1);
}

const client = new Client({
  intents: [GatewayIntentBits.Guilds],
});

// Sleep helper to prevent Discord rate limits
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

client.once("ready", async () => {
  console.log(\`[+] Logged in as \${client.user.tag}\`);
  console.log(\`[+] Mode: \${IS_DRY_RUN ? "DRY-RUN (Simulating changes, no live edits)" : "LIVE EXECUTION"}\`);

  try {
    const guild = await client.guilds.fetch(GUILD_ID);
    if (!guild) {
      throw new Error(\`Guild with ID \${GUILD_ID} not found. Ensure bot is invited.\`);
    }
    console.log(\`[+] Target Server: \${guild.name} (\${guild.id})\`);

    // ── 1. Create Roles ────────────────────────
    const roleMap = new Map();
    console.log("\\n--- Step 1: Synchronizing Roles ---");
    ${
      norm.roles.length === 0
        ? `console.log("No custom roles defined in template/proposal.");`
        : `const rolesToCreate = ${JSON.stringify(norm.roles, null, 2)};

    for (const rData of rolesToCreate) {
      const existing = guild.roles.cache.find(r => r.name.toLowerCase() === rData.name.toLowerCase());
      if (existing) {
        console.log(\`  [=] Role "\${rData.name}" already exists (\${existing.id}).\`);
        roleMap.set(rData.name, existing);
      } else if (!IS_DRY_RUN) {
        const created = await guild.roles.create({
          name: rData.name,
          color: rData.color || undefined,
          reason: "MapMyServer Architecture Automation",
        });
        console.log(\`  [+] Created Role "\${created.name}" (\${created.id}).\`);
        roleMap.set(rData.name, created);
        await sleep(350);
      } else {
        console.log(\`  [*] [DRY-RUN] Would create role "\${rData.name}".\`);
      }
    }`
    }

    // ── 2. Create Categories & Channels ────────
    console.log("\\n--- Step 2: Synchronizing Categories & Channels ---");
    const categoriesToCreate = ${JSON.stringify(norm.categories, null, 2)};

    for (const catData of categoriesToCreate) {
      let category = guild.channels.cache.find(
        c => c.type === ChannelType.GuildCategory && c.name.toLowerCase() === catData.name.toLowerCase()
      );

      if (category) {
        console.log(\`\\n[=] Category "\${catData.name}" exists (\${category.id}).\`);
      } else if (!IS_DRY_RUN) {
        category = await guild.channels.create({
          name: catData.name,
          type: ChannelType.GuildCategory,
          reason: "MapMyServer Architecture Automation",
        });
        console.log(\`\\n[+] Created Category "\${category.name}" (\${category.id}).\`);
        await sleep(400);
      } else {
        console.log(\`\\n[*] [DRY-RUN] Would create Category "\${catData.name}".\`);
      }

      // Channels inside category
      for (const chData of catData.channels) {
        const existingChan = guild.channels.cache.find(
          c => c.parentId === category?.id && c.name.toLowerCase() === chData.name.toLowerCase()
        );

        if (existingChan) {
          console.log(\`  [=] Channel "#\${chData.name}" exists.\`);
          continue;
        }

        const channelType = chData.type === "voice"
          ? ChannelType.GuildVoice
          : chData.type === "forum"
          ? ChannelType.GuildForum
          : chData.type === "announcement"
          ? ChannelType.GuildAnnouncement
          : ChannelType.GuildText;

        if (!IS_DRY_RUN) {
          const newChan = await guild.channels.create({
            name: chData.name,
            type: channelType,
            parent: category?.id,
            topic: chData.topic || undefined,
            reason: "MapMyServer Architecture Automation",
          });
          console.log(\`  [+] Created \${chData.type} channel "#\${newChan.name}" (\${newChan.id}).\`);
          await sleep(350);
        } else {
          console.log(\`  [*] [DRY-RUN] Would create \${chData.type} channel "#\${chData.name}".\`);
        }
      }
    }

    console.log("\\n[✓] Automation complete successfully!");
  } catch (err) {
    console.error("\\n[!] Automation error:", err);
  } finally {
    client.destroy();
  }
});

client.login(TOKEN);
`;
}

// ── Discord.py Generator ───────────────────────

export function generateDiscordPyScript(
  source: ArchitectureSource,
  options: ScriptGeneratorOptions = {}
): string {
  const norm = normalizeSource(source);
  const guildId = options.guildId || "YOUR_TARGET_GUILD_ID";
  const isDryRun = options.dryRun ?? false;

  return `"""
Discord Server Architecture Automation Script (discord.py v2)
Target Server: ${norm.name}
Generated by MapMyServer

PREREQUISITES:
1. pip install discord.py python-dotenv
2. Set DISCORD_BOT_TOKEN in your .env file
3. Ensure bot has Administrator or Manage Channels & Roles

EXECUTION:
python apply_architecture.py ${isDryRun ? "--dry-run" : ""}
"""

import os
import sys
import asyncio
import discord
from dotenv import load_dotenv

load_dotenv()

TOKEN = os.getenv("DISCORD_BOT_TOKEN")
GUILD_ID = int(os.getenv("DISCORD_GUILD_ID", "${guildId.match(/^\d+$/) ? guildId : 0}"))
IS_DRY_RUN = "--dry-run" in sys.argv or ${isDryRun ? "True" : "False"}

if not TOKEN:
    print("ERROR: DISCORD_BOT_TOKEN is required in environment variables.")
    sys.exit(1)

intents = discord.Intents.default()
client = discord.Client(intents=intents)

CATEGORIES_DATA = ${JSON.stringify(norm.categories, null, 4).replace(/true/g, "True").replace(/false/g, "False").replace(/null/g, "None")}

ROLES_DATA = ${JSON.stringify(norm.roles, null, 4).replace(/true/g, "True").replace(/false/g, "False").replace(/null/g, "None")}

@client.event
async def on_ready():
    print(f"[+] Logged in as {client.user} (ID: {client.user.id})")
    print(f"[+] Mode: {'DRY-RUN (Simulating changes)' if IS_DRY_RUN else 'LIVE EXECUTION'}")

    try:
        guild = client.get_guild(GUILD_ID) or await client.fetch_guild(GUILD_ID)
        if not guild:
            print(f"[!] Guild ID {GUILD_ID} not found. Ensure bot is invited.")
            return

        print(f"[+] Target Guild: {guild.name} ({guild.id})")

        # ── 1. Create Roles ──
        print("\\n--- Step 1: Synchronizing Roles ---")
        for r_data in ROLES_DATA:
            existing = discord.utils.get(guild.roles, name=r_data["name"])
            if existing:
                print(f"  [=] Role '{r_data['name']}' already exists.")
            elif not IS_DRY_RUN:
                created = await guild.create_role(name=r_data["name"], reason="MapMyServer Automation")
                print(f"  [+] Created role '{created.name}'.")
                await asyncio.sleep(0.4)
            else:
                print(f"  [*] [DRY-RUN] Would create role '{r_data['name']}'.")

        # ── 2. Create Categories & Channels ──
        print("\\n--- Step 2: Synchronizing Categories & Channels ---")
        for cat_data in CATEGORIES_DATA:
            category = discord.utils.get(guild.categories, name=cat_data["name"])
            if category:
                print(f"\\n[=] Category '{cat_data['name']}' exists.")
            elif not IS_DRY_RUN:
                category = await guild.create_category(name=cat_data["name"], reason="MapMyServer Automation")
                print(f"\\n[+] Created category '{category.name}'.")
                await asyncio.sleep(0.4)
            else:
                print(f"\\n[*] [DRY-RUN] Would create category '{cat_data['name']}'.")

            for ch_data in cat_data["channels"]:
                ch_name = ch_data["name"]
                ch_type = ch_data["type"]
                topic = ch_data.get("topic")

                existing_ch = discord.utils.get(guild.channels, name=ch_name, category=category)
                if existing_ch:
                    print(f"  [=] Channel '#{ch_name}' exists.")
                    continue

                if not IS_DRY_RUN:
                    if ch_type == "voice":
                        new_ch = await guild.create_voice_channel(name=ch_name, category=category)
                    elif ch_type == "forum":
                        new_ch = await guild.create_forum_channel(name=ch_name, category=category, topic=topic)
                    else:
                        new_ch = await guild.create_text_channel(name=ch_name, category=category, topic=topic)
                    print(f"  [+] Created {ch_type} channel '#{new_ch.name}'.")
                    await asyncio.sleep(0.4)
                else:
                    print(f"  [*] [DRY-RUN] Would create {ch_type} channel '#{ch_name}'.")

        print("\\n[✓] Automation complete successfully!")
    except Exception as e:
        print(f"[!] Error: {e}")
    finally:
        await client.close()

client.run(TOKEN)
`;
}
